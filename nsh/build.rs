//! Compile ARB catalogs and SVG assets into deterministic, typed Rust tables.
use std::{
    collections::{BTreeMap, BTreeSet},
    env,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

fn files(directory: &Path, extension: &str) -> Vec<PathBuf> {
    let mut result = Vec::new();
    for entry in fs::read_dir(directory).expect("read asset directory") {
        let path = entry.expect("read asset entry").path();
        if path.is_dir() {
            result.extend(files(&path, extension));
        } else if path.extension().is_some_and(|value| value == extension) {
            result.push(path);
        }
    }
    result.sort();
    result
}

fn variant(key: &str) -> String {
    assert!(
        key.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
            && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'),
        "ARB key must be a Rust identifier: {key}"
    );
    let mut name = key.to_owned();
    name[..1].make_ascii_uppercase();
    name
}

fn catalogs(output: &Path) {
    let mut catalogs = BTreeMap::new();
    for path in files(Path::new("assets/l10n"), "arb") {
        let filename = path.file_stem().unwrap().to_str().unwrap();
        let Some(locale) = filename.strip_prefix("intl_") else {
            continue;
        };
        let source = fs::read_to_string(&path).expect("read ARB");
        let values: BTreeMap<String, serde_json::Value> = serde_json::from_str(&source)
            .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
        let messages: BTreeMap<_, _> = values
            .into_iter()
            .filter(|(key, _)| !key.starts_with('@'))
            .map(|(key, value)| {
                let message = value.as_str().unwrap_or_else(|| {
                    panic!("{}: message {key} must be a string", path.display())
                });
                (key, message.to_owned())
            })
            .collect();
        let locale = match locale {
            "in" => "id",
            "zh" => "zh-CN",
            other => other,
        };
        assert!(catalogs.insert(locale.to_owned(), messages).is_none());
    }
    let english = catalogs.get("en").expect("English ARB catalog");
    for locale in ["zh-CN", "zh-TW", "zh-HK"] {
        let messages = catalogs.get(locale).expect("Chinese ARB catalog");
        for key in english.keys().filter(|key| key.starts_with("nsh")) {
            assert!(
                messages.contains_key(key),
                "NSH message {key} is missing from {locale}"
            );
        }
    }
    let keys: Vec<_> = english.keys().collect();
    let mut names = BTreeSet::new();
    let mut code = String::from(
        "// Generated by build.rs. Edit assets/l10n/intl_*.arb instead.\n\
         #[allow(dead_code, non_camel_case_types)]\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
         pub(crate) enum Key {\n",
    );
    for key in &keys {
        let name = variant(key);
        assert!(names.insert(name.clone()), "colliding ARB key: {key}");
        writeln!(code, "    {name},").unwrap();
    }
    code.push_str("}\n#[cfg(test)]\npub(super) const KEYS: &[Key] = &[\n");
    for key in &keys {
        writeln!(code, "    Key::{},", variant(key)).unwrap();
    }
    code.push_str("];\npub(crate) fn lookup(locale: &str, key: Key) -> &'static str {\n    let messages: &[&str; ");
    write!(code, "{}] = match locale {{", keys.len()).unwrap();
    // Materialize fallback at build time, so runtime lookup is one array index.
    for (locale, messages) in &catalogs {
        if locale == "en" {
            continue;
        }
        writeln!(code, "\n        {locale:?} => &[").unwrap();
        for key in &keys {
            let value = messages.get(*key).unwrap_or(&english[*key]);
            writeln!(code, "            {value:?},").unwrap();
        }
        code.push_str("        ],");
    }
    code.push_str("\n        _ => &[\n");
    for value in english.values() {
        writeln!(code, "            {value:?},").unwrap();
    }
    code.push_str("        ],\n    };\n    messages[key as usize]\n}\n");
    fs::write(output.join("i18n.rs"), code).expect("write generated catalog");
}

fn svg_assets(output: &Path) {
    let assets = files(Path::new("assets"), "svg");
    let mut names = BTreeSet::new();
    let mut code = String::from("// Generated by build.rs. Edit assets/**/*.svg instead.\n");
    let mut all = String::from("#[cfg(test)]\npub(crate) const ALL: &[(&str, &str)] = &[\n");
    for path in assets {
        let relative = path
            .strip_prefix("assets")
            .unwrap()
            .to_str()
            .unwrap()
            .replace('\\', "/");
        let name: String = relative[..relative.len() - 4]
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() {
                    c.to_ascii_uppercase()
                } else {
                    '_'
                }
            })
            .collect();
        assert!(
            names.insert(name.clone()),
            "colliding SVG asset: {relative}"
        );
        assert!(
            name.starts_with(|c: char| c.is_ascii_alphabetic()),
            "invalid SVG name: {relative}"
        );
        let source = format!("/assets/{relative}");
        writeln!(code, "pub(crate) const {name}: &str = include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {source:?}));").unwrap();
        writeln!(all, "    ({relative:?}, {name}),").unwrap();
    }
    all.push_str("];\n");
    code.push_str(&all);
    fs::write(output.join("svg.rs"), code).expect("write generated SVG assets");
}

fn main() {
    println!("cargo:rerun-if-changed=assets/l10n");
    println!("cargo:rerun-if-changed=assets");
    let output = PathBuf::from(env::var_os("OUT_DIR").expect("Cargo OUT_DIR"));
    catalogs(&output);
    svg_assets(&output);
}
